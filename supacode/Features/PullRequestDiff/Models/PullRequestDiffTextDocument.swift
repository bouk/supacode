import Foundation

/// The text view's UTF-16 index, separate from gutters so copied code contains
/// the original tabs and characters, without line numbers or +/- markers.
nonisolated struct PullRequestDiffTextDocument: Sendable {
  let document: PullRequestDiffDocument
  let text: String
  let rowRanges: [NSRange]

  init(document: PullRequestDiffDocument, collapsedFiles: Set<Int> = []) {
    self.document = document
    var text = ""
    var ranges: [NSRange] = []
    ranges.reserveCapacity(document.rows.count)
    var offset = 0
    for row in document.rows {
      if row.kind != .fileHeader, collapsedFiles.contains(Int(row.fileIndex)) {
        ranges.append(NSRange(location: offset, length: 0))
        continue
      }
      let line: String
      if row.kind == .fileHeader {
        let file = document.files[Int(row.fileIndex)]
        let name = file.oldPath.map { $0 + " → " + file.path } ?? file.path
        line =
          (collapsedFiles.contains(file.id) ? "▸ " : "▾ ") + name
          + (Self.isGenerated(file, in: document) ? "  (Generated)" : "")
          + (file.isBinary ? "  (Binary)" : "  +\(file.additions) −\(file.deletions)")
      } else {
        line = String(row.text)
      }
      let length = line.utf16.count + 1
      ranges.append(NSRange(location: offset, length: length))
      text += line + "\n"
      offset += length
    }
    self.text = text
    rowRanges = ranges
  }

  func row(atUTF16Offset offset: Int) -> Int? {
    guard offset >= 0, let last = rowRanges.last, offset < NSMaxRange(last) else { return nil }
    var lower = 0
    var upper = rowRanges.count
    while lower < upper {
      let middle = (lower + upper) / 2
      if NSMaxRange(rowRanges[middle]) <= offset { lower = middle + 1 } else { upper = middle }
    }
    return lower < rowRanges.count ? lower : nil
  }

  @concurrent
  static func search(_ text: String, for query: String) async -> [NSRange] {
    guard !query.isEmpty else { return [] }
    let source = text as NSString
    var matches: [NSRange] = []
    var start = 0
    while start < source.length {
      if Task.isCancelled { return [] }
      let range = source.range(
        of: query, options: [.caseInsensitive], range: NSRange(location: start, length: source.length - start))
      guard range.location != NSNotFound, range.length > 0 else { break }
      matches.append(range)
      start = NSMaxRange(range)
    }
    return matches
  }

  static func isGenerated(_ file: PullRequestDiffFile, in document: PullRequestDiffDocument) -> Bool {
    if let explicit = document.generatedFileAttributes[file.path] { return explicit }
    let path = file.path.lowercased()
    let name = file.name.lowercased()
    let locks: Set<String> = [
      "package-lock.json", "npm-shrinkwrap.json", "yarn.lock", "pnpm-lock.yaml", "bun.lock", "bun.lockb",
      "cargo.lock", "flake.lock", "poetry.lock", "uv.lock", "pipfile.lock", "composer.lock", "gemfile.lock",
      "package.resolved",
    ]
    if locks.contains(name) || path.hasSuffix(".min.js") || path.hasSuffix(".min.css") || path.hasSuffix(".map")
      || path.contains(".generated.") || path.contains("_generated.")
      || path.split(separator: "/").contains(where: { ["generated", "__generated__"].contains($0) })
    {
      return true
    }
    let rows = document.rows
    let end = min(file.headerRow + 25, rows.count)
    for row in rows[(file.headerRow + 1)..<end] where Int(row.fileIndex) == file.id && row.kind != .deletion {
      let text = row.text.trimmingCharacters(in: .whitespaces).lowercased()
      guard ["//", "#", "/*", "*", "<!--"].contains(where: text.hasPrefix) else { continue }
      if [
        "@generated", "auto-generated", "autogenerated", "automatically generated", "code generated", "generated by",
        "do not edit",
      ].contains(where: text.contains) {
        return true
      }
    }
    return false
  }

}
